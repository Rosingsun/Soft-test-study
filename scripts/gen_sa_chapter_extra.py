def esc(s):
    return s.replace("\\", "\\\\").replace("'", "''")


def build_sql():
    lines = ["SET NAMES utf8mb4;", "-- 「系统分析师-综合知识」章节补充题库（自动生成，勿手工修改）"]
    total = 0
    for ch_id, items in BANK.items():
        total += len(items)
        for content, opts, answer, diff, analysis in items:
            opts_json = "[" + ", ".join(f'"{esc(o)}"' for o in opts) + "]"
            row = (
                f"({SUBJECT_ID}, {SUB_SUBJECT_ID}, {ch_id}, 0, 'single', '{diff}', "
                f"'{esc(content)}', '', '{opts_json}', '[]', "
                f"'{answer}', '{esc(analysis)}', {YEAR}, '{SOURCE}', 1, NOW(), NOW())"
            )
            lines.append("INSERT INTO `questions` (`subject_id`,`sub_subject_id`,`chapter_id`,`parent_id`,"
                         "`type`,`difficulty`,`content`,`case_material`,`options`,`blank_options`,`answer`,"
                         "`analysis`,`year`,`source`,`status`,`created_at`,`updated_at`) VALUES")
            lines.append(row + ";")
    print(f"共生成 {total} 道补充题")
    out_path = os.path.join(os.path.dirname(__file__), "..", "sa_chapter_extra.sql")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"SQL 已写入 {os.path.abspath(out_path)}")
    return os.path.abspath(out_path)


def main():
    sql_path = build_sql()
    if APPLY:
        env = dict(os.environ)
        env["MYSQL_PWD"] = "C5SbSrEzBBLSZBaZ"
        with open(sql_path, "rb") as f:
            r = subprocess.run([MYSQL] + DB_ARGS, stdin=f,
                               capture_output=True, env=env)
        if r.returncode == 0:
            print("导入完成")
        else:
            print("导入失败:", r.stderr.decode("utf-8", errors="replace")[:800])
            sys.exit(1)


