def main():
    banks = load_all_banks()

    lines = [
        "-- =============================================================",
        "-- 软考学系平台 - 题目种子数据（第二批）",
        "-- 每科目 × 每题型 × 每难度 各 10 题，共 600 题",
        "-- =============================================================",
        f"USE `{DB}`;",
        "",
    ]

    total = 0
    for sid, (sname, ssid) in SUBJECTS.items():
        for qtype in ("single", "multi", "judge", "fill"):
            for diff in ("easy", "medium", "hard"):
                qs = banks[sid][qtype][diff]
                assert len(qs) >= 10, f"{sid} {qtype} {diff} only {len(qs)}"
                qs = qs[:10]
                lines.append(f"-- {sname} — {TYPE_LABEL[qtype]} — {DIFF_LABEL[diff]}")
                lines.append(
                    "INSERT INTO `questions` (`subject_id`, `sub_subject_id`, `type`, `difficulty`, "
                    "`content`, `options`, `answer`, `analysis`, `year`, `status`, `created_at`) VALUES"
                )
                rows = [fmt_row(sid, ssid, qtype, diff, *q) for q in qs]
                lines.append(",\n\n".join(rows) + ";")
                lines.append("")
                total += len(qs)

    lines.append(f"-- 共插入 {total} 条记录")
    content = "\n".join(lines)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Generated {total} questions -> {OUT}")


if __name__ == "__main__":
    main()
