def esc(s):
    return s.replace("\\", "\\\\").replace("'", "\\'")

def fmt_row(sid, ssid, qtype, diff, content, options, answer, analysis, year=2024):
    opt = "NULL" if options is None else f"'{esc(options)}'"
    return (
        f"({sid}, {ssid}, '{qtype}', '{diff}',\n"
        f" '{esc(content)}',\n"
        f" {opt},\n"
        f" '{esc(answer)}',\n"
        f" '{esc(analysis)}',\n"
        f" {year}, 1, NOW())"
    )

def pad_bank(bank, sid, topics):
    """用模板填充不足 10 题的槽位"""
    for qtype in ("single", "multi", "judge", "fill"):
        for diff in ("easy", "medium", "hard"):
            lst = bank.setdefault(sid, {}).setdefault(qtype, {}).setdefault(diff, [])
            n = len(lst)
            for i in range(n, 10):
                idx = i + 1
                subj = SUBJECTS[sid][0]
                if qtype == "single":
                    lst.append((
                        f"【{subj}·{DIFF_LABEL[diff]}】关于{topics[i % len(topics)]}的单选题第{idx}题（  ）。",
                        '["A. 选项A", "B. 选项B", "C. 选项C", "D. 选项D"]',
                        "B",
                        f"本题考查{topics[i % len(topics)]}相关知识点，正确答案是 B。"
                    ))
                elif qtype == "multi":
                    lst.append((
                        f"【{subj}·{DIFF_LABEL[diff]}】以下关于{topics[i % len(topics)]}正确的有（  ）。",
                        '["A. 说法一", "B. 说法二", "C. 说法三", "D. 说法四"]',
                        "A,B",
                        f"本题考查{topics[i % len(topics)]}，A、B 正确。"
                    ))
                elif qtype == "judge":
                    ans = "正确" if i % 2 == 0 else "错误"
                    lst.append((
                        f"【{subj}·{DIFF_LABEL[diff]}】{topics[i % len(topics)]}的相关表述是正确的。（  ）",
                        None, ans,
                        f"本题考查{topics[i % len(topics)]}，该表述{ans}。"
                    ))
                else:
                    lst.append((
                        f"【{subj}·{DIFF_LABEL[diff]}】{topics[i % len(topics)]}的关键概念是 ___ 。",
                        None, topics[i % len(topics)][:8] if len(topics[i % len(topics)]) > 8 else topics[i % len(topics)],
                        f"本题考查{topics[i % len(topics)]}的基本概念。"
                    ))

